package br.edu.unieuro.loja.db;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;

/** Cria as tabelas e os produtos de demonstracao na primeira execucao do H2. */
public final class DatabaseInitializer {
    private DatabaseInitializer() {
    }

    public static void initialize() throws SQLException {
        try (Connection connection = Database.getConnection();
             Statement statement = connection.createStatement()) {
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS cliente (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nome VARCHAR(120) NOT NULL,
                        email VARCHAR(180) UNIQUE
                    )
                    """);
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS produto (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        codigo VARCHAR(30) NOT NULL UNIQUE,
                        nome VARCHAR(120) NOT NULL,
                        categoria VARCHAR(80) NOT NULL,
                        quantidade_estoque INTEGER NOT NULL DEFAULT 0 CHECK (quantidade_estoque >= 0),
                        preco NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (preco >= 0)
                    )
                    """);
            statement.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS entrada_estoque (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        produto_id BIGINT NOT NULL REFERENCES produto(id),
                        quantidade INTEGER NOT NULL CHECK (quantidade > 0),
                        data_entrada TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        observacao VARCHAR(500)
                    )
                    """);
            statement.executeUpdate("""
                    CREATE INDEX IF NOT EXISTS idx_entrada_estoque_produto_id
                    ON entrada_estoque(produto_id)
                    """);
        }

        inserirProdutoSeNaoExistir("MOU001", "Mouse USB", "Informatica", 12, new BigDecimal("29.90"));
        inserirProdutoSeNaoExistir("TEC001", "Teclado USB", "Informatica", 8, new BigDecimal("59.90"));
        inserirProdutoSeNaoExistir("CAB001", "Cabo HDMI 2m", "Acessorios", 15, new BigDecimal("24.50"));
    }

    private static void inserirProdutoSeNaoExistir(String codigo, String nome, String categoria,
                                                   int quantidade, BigDecimal preco) throws SQLException {
        String sql = """
                INSERT INTO produto (codigo, nome, categoria, quantidade_estoque, preco)
                SELECT ?, ?, ?, ?, ?
                WHERE NOT EXISTS (SELECT 1 FROM produto WHERE codigo = ?)
                """;
        try (Connection connection = Database.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, codigo);
            statement.setString(2, nome);
            statement.setString(3, categoria);
            statement.setInt(4, quantidade);
            statement.setBigDecimal(5, preco);
            statement.setString(6, codigo);
            statement.executeUpdate();
        }
    }
}
